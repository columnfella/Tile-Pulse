#!/usr/bin/env node
/**
 * The website uses the game's DEFAULT theme (Dusty Dusk), always: it has no
 * theme picker. Before every build / dev start this reads the game's theme file
 * (game/src/theme/themes.json) and writes:
 *   - src/app/theme.generated.css   CSS variables (:root) for every colour
 *   - src/content/theme.json        the same colours for TypeScript (shader, meta tags)
 * Change the default theme in the game and the website follows on its next build.
 *
 * Runs automatically: "predev" and "prebuild" in package.json.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const themesFile = path.join(here, '..', '..', 'game', 'src', 'theme', 'themes.json');
const cssOut = path.join(here, '..', 'src', 'app', 'theme.generated.css');
const jsonOut = path.join(here, '..', 'src', 'content', 'theme.json');

// Dusty Dusk, used if the website is ever built without the game folder next to it
const FALLBACK = {
  id: 'dusty_dusk',
  name: 'Dusty Dusk',
  colors: {
    background: '#211F2B', backgroundSecondary: '#272433', surface: '#2D293A', surfaceHover: '#383346',
    surfaceActive: '#443E56', border: '#403A4D', primary: '#9890AD', primaryHover: '#B2A9C8',
    secondary: '#77728E', highlight: '#C2B5B0', text: '#EAE6F0', textMuted: '#AAA4B5',
    success: '#91AA99', error: '#C98289',
  },
};

let theme = FALLBACK;
try {
  const file = JSON.parse(fs.readFileSync(themesFile, 'utf8'));
  theme = file.themes.find((t) => t.id === file.default) ?? FALLBACK;
} catch {
  console.warn('theme: game/src/theme/themes.json not found, using Dusty Dusk');
}

const rgb = (hex) => {
  const n = parseInt(hex.replace('#', '').slice(0, 6), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
};
const hex = (c) => '#' + c.map((v) => Math.round(v).toString(16).padStart(2, '0')).join('');
// Same blends as the game (src/theme/palette.ts → derivePalette)
const mix = (a, b, t) => hex(rgb(a).map((v, i) => v + (rgb(b)[i] - v) * t));

const c = theme.colors;
const colors = {
  ...c,
  ink: mix(c.background, '#000000', 0.6), // pixel outlines and shadows
  onPrimary: mix(c.background, '#000000', 0.4), // text on primary buttons (same as the game)
  textFaint: mix(c.textMuted, c.background, 0.28),
  warning: mix('#d4b06a', c.highlight, 0.1), // muted amber (Early Tester banner)
};

const kebab = (k) => k.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase());
const lines = Object.entries(colors).flatMap(([k, v]) => [
  `  --${kebab(k)}: ${v};`,
  // "r, g, b" for see-through versions: rgba(var(--surface-rgb), 0.6)
  `  --${kebab(k)}-rgb: ${rgb(v).join(', ')};`,
]);

fs.writeFileSync(
  cssOut,
  `/* Generated by scripts/theme-css.mjs from the game's default theme (${theme.name}). Do not edit. */\n:root {\n${lines.join('\n')}\n}\n`
);
fs.writeFileSync(jsonOut, JSON.stringify({ id: theme.id, name: theme.name, colors }, null, 2) + '\n');
console.log(`website theme: ${theme.name}`);
