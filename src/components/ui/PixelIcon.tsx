export type PixelIconName = keyof typeof BITMAPS;

interface PixelIconProps {
  name: PixelIconName;
  /** Total icon size in px (rounded down to a whole number of pixels per cell). */
  size?: number;
  color: string;
}

export const PixelIcon = memo(function PixelIcon({ name, size = 22, color }: PixelIconProps) {
  const bitmap = BITMAPS[name];
  const cols = bitmap[0].length;
  const cell = Math.max(1, Math.floor(size / cols)); // whole pixels keep edges crisp
  const dim = cell * cols;

  const runs = useMemo(() => {
    const out: { x: number; y: number; w: number }[] = [];
    bitmap.forEach((row, y) => {
      let start = -1;
      for (let x = 0; x <= row.length; x++) {
        const on = row[x] === '#';
        if (on && start < 0) start = x;
        if (!on && start >= 0) {
          out.push({ x: start, y, w: x - start });
          start = -1;
        }
      }
    });
    return out;
  }, [bitmap]);

  return (
    <View style={{ width: dim, height: cell * bitmap.length }}>
      {runs.map((r, i) => (
        <View
          key={i}
          style={{
            position: 'absolute',
            left: r.x * cell,
            top: r.y * cell,
            width: r.w * cell,
            height: cell,
            backgroundColor: color,
          }}
        />
      ))}
    </View>
  );
});
